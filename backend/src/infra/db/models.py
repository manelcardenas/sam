class MealPlanModel(Base):
    """One person's week (docs/plans/meal-planner-plan.md §8.3)."""

    __tablename__ = "meal_plans"

    __table_args__ = (
        # One plan per person per week. The owner is in the key because a plan
        # belongs to a person (§4.2) — two people planning the same week is
        # normal, and the same person planning it twice is not.
        Index("uq_meal_plans_owner_week", "owner_id", "week_start", unique=True),
    )

    id: Mapped[PythonUUID] = mapped_column(UUID(as_uuid=True), primary_key=True, server_default=func.gen_random_uuid())
    owner_id: Mapped[str] = mapped_column(String, ForeignKey("users.id"), nullable=False)
    week_start: Mapped[date] = mapped_column(
        Date, nullable=False, comment="Always a Saturday — the week runs Sat→Fri, normalised server-side so one week can't exist twice"
    )
    # `values_callable` is load-bearing: without it SQLAlchemy persists the
    # member *name* ("PLANNING"), while the migration created the type with the
    # lowercase *values*. The insert then fails with
    # `invalid input value for enum plan_status_enum: "PLANNING"`.
    #
    # This differs from `recipes.food_type`, whose type was created with
    # uppercase names back when the default was simply accepted. Storing the
    # value is the better of the two — the column then reads the same as the API
    # and the docs — so new enums use it, and food_type is left alone because
    # changing it now is a data migration for no behavioural gain.
    status: Mapped[PlanStatus] = mapped_column(
        Enum(PlanStatus, name="plan_status_enum", values_callable=lambda enum: [member.value for member in enum]),
        nullable=False,
        server_default="planning",
    )
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False, server_default=func.now())
    updated_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False, server_default=func.now(), onupdate=func.now())

    owner: Mapped["UserModel"] = relationship(lazy="joined")
    # Read-and-tick guests (§4.3). A secondary relationship rather than a mapped
    # class, because the row carries no data of its own — adding `can_edit` later
    # is when it earns one.
    shared_with: Mapped[list["UserModel"]] = relationship(secondary=plan_shares, lazy="selectin")
    # selectin rather than joined: a plan pulls at most ten entries and a few
    # dozen list lines, and joining both onto one row would multiply them out.
    entries: Mapped[list["PlanEntryModel"]] = relationship(back_populates="plan", lazy="selectin", cascade="all, delete-orphan")
    items: Mapped[list["ShoppingListItemModel"]] = relationship(back_populates="plan", lazy="selectin", cascade="all, delete-orphan")


class PlanEntryModel(Base):
    """A dish in a slot, for a stated headcount."""

    __tablename__ = "plan_entries"

    __table_args__ = (
        CheckConstraint("servings >= 1", name="ck_plan_entries_servings_positive"),
        # One dish per slot in v1 (§6). Starter-plus-main later is dropping this.
        Index("uq_plan_entries_slot", "plan_id", "date", "meal", unique=True),
    )

    id: Mapped[PythonUUID] = mapped_column(UUID(as_uuid=True), primary_key=True, server_default=func.gen_random_uuid())
    plan_id: Mapped[PythonUUID] = mapped_column(UUID(as_uuid=True), ForeignKey("meal_plans.id", ondelete="CASCADE"), nullable=False, index=True)
    date: Mapped[date] = mapped_column(Date, nullable=False)
    # Same reason as MealPlanModel.status — the migration created this type with
    # lowercase values, and the default would send "LUNCH".
    meal: Mapped[Meal] = mapped_column(
        Enum(Meal, name="meal_enum", values_callable=lambda enum: [member.value for member in enum]),
        nullable=False,
    )
    # SET NULL, never CASCADE: deleting a recipe in November must not empty out
    # what you ate in August. The snapshot below keeps the row readable.
    recipe_id: Mapped[PythonUUID | None] = mapped_column(
        UUID(as_uuid=True), ForeignKey("recipes.id", ondelete="SET NULL"), nullable=True, comment="NULL once the recipe is deleted"
    )
    dish_name: Mapped[str] = mapped_column(String(255), nullable=False, comment="Snapshot — the plan records what you ate, not a live view of the collection")
    servings: Mapped[int] = mapped_column(Integer, nullable=False)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False, server_default=func.now())

    plan: Mapped["MealPlanModel"] = relationship(back_populates="entries")


class ShoppingListItemModel(Base):
    """One line on the list — a merged total with its provenance (§4.6)."""

    __tablename__ = "shopping_list_items"

    __table_args__ = (
        # COALESCE, not a bare `unit`: Postgres treats NULLs as distinct in a
        # unique constraint, and most household ingredients have no unit — so
        # indexing `unit` directly fails to merge the *common* case. The upsert
        # in postgres_meal_plan_repo.py uses the same expression.
        Index("uq_shopping_list_items_merge_key", "plan_id", "normalised_name", text("COALESCE(unit, '')"), unique=True),
    )

    id: Mapped[PythonUUID] = mapped_column(UUID(as_uuid=True), primary_key=True, server_default=func.gen_random_uuid())
    plan_id: Mapped[PythonUUID] = mapped_column(UUID(as_uuid=True), ForeignKey("meal_plans.id", ondelete="CASCADE"), nullable=False, index=True)
    display_name: Mapped[str] = mapped_column(String(255), nullable=False, comment="As first typed — the list reads in the user's own words")
    normalised_name: Mapped[str] = mapped_column(String(255), nullable=False, comment="Merge key: lowercased, whitespace-collapsed, diacritics stripped")
    unit: Mapped[str | None] = mapped_column(String(50), nullable=True)
    total_amount: Mapped[float | None] = mapped_column(Numeric(10, 3), nullable=True, comment="NULL for things with no quantity — 'sal' is a real ingredient")
    is_checked: Mapped[bool] = mapped_column(Boolean, nullable=False, server_default=text("false"))
    is_manual: Mapped[bool] = mapped_column(Boolean, nullable=False, server_default=text("false"))
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False, server_default=func.now())
    updated_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False, server_default=func.now(), onupdate=func.now())

    plan: Mapped["MealPlanModel"] = relationship(back_populates="items")
    sources: Mapped[list["ListItemSourceModel"]] = relationship(back_populates="item", lazy="selectin", cascade="all, delete-orphan")


class ListItemSourceModel(Base):
    """Which dish put this line on the list, and how much of it it accounts for.

    The breakdown half of §4.6: a merged total is what you need at the shelf, and
    provenance is what answers *"why is there fennel on this list?"*.
    """

    __tablename__ = "list_item_sources"

    id: Mapped[PythonUUID] = mapped_column(UUID(as_uuid=True), primary_key=True, server_default=func.gen_random_uuid())
    item_id: Mapped[PythonUUID] = mapped_column(UUID(as_uuid=True), ForeignKey("shopping_list_items.id", ondelete="CASCADE"), nullable=False, index=True)
    entry_id: Mapped[PythonUUID | None] = mapped_column(
        UUID(as_uuid=True), ForeignKey("plan_entries.id", ondelete="SET NULL"), nullable=True, index=True, comment="NULL for manual extras and once the entry is gone"
    )
    dish_name: Mapped[str] = mapped_column(String(255), nullable=False, comment="Snapshot — survives the recipe being deleted")
    amount: Mapped[float | None] = mapped_column(Numeric(10, 3), nullable=True)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False, server_default=func.now())

    item: Mapped["ShoppingListItemModel"] = relationship(back_populates="sources")
