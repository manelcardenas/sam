    item_id: Mapped[PythonUUID] = mapped_column(UUID(as_uuid=True), ForeignKey("shopping_list_items.id", ondelete="CASCADE"), nullable=False, index=True)
    entry_id: Mapped[PythonUUID | None] = mapped_column(
        UUID(as_uuid=True), ForeignKey("plan_entries.id", ondelete="SET NULL"), nullable=True, index=True, comment="NULL for manual extras and once the entry is gone"
    )
    dish_name: Mapped[str] = mapped_column(String(255), nullable=False, comment="Snapshot — survives the recipe being deleted")
    amount: Mapped[float | None] = mapped_column(Numeric(10, 3), nullable=True)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False, server_default=func.now())

    item: Mapped["ShoppingListItemModel"] = relationship(back_populates="sources")
