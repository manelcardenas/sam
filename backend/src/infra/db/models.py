from datetime import datetime
from uuid import UUID as PythonUUID  # noqa: N811 — alias avoids collision with SQLAlchemy's UUID dialect type

from sqlalchemy import CheckConstraint, DateTime, Enum, ForeignKey, Integer, String, Text, func
from sqlalchemy.dialects.postgresql import JSONB, UUID
from sqlalchemy.orm import Mapped, mapped_column

from src.domain.entities import FoodType
from src.infra.db.base import Base


class UserModel(Base):
    __tablename__ = "users"

    __table_args__ = (CheckConstraint("email LIKE '%@%'", name="ck_users_email_format"),)

    id: Mapped[str] = mapped_column(String, primary_key=True, comment="Cognito sub")
    display_name: Mapped[str] = mapped_column(String(50), unique=True, nullable=False, comment="Name decided by the user")
    email: Mapped[str] = mapped_column(String(255), unique=True, nullable=False)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False, server_default=func.now())
    updated_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False, server_default=func.now(), onupdate=func.now())


class RecipeModel(Base):
    __tablename__ = "recipes"

    id: Mapped[PythonUUID] = mapped_column(UUID(as_uuid=True), primary_key=True, server_default=func.gen_random_uuid())  # generated by PostgreSQL
    # Core
    title: Mapped[str] = mapped_column(String(255), nullable=False)
    instructions: Mapped[str] = mapped_column(Text, nullable=False)
    food_type: Mapped[FoodType] = mapped_column(Enum(FoodType, name="food_type_enum"), nullable=False)

    # Ingredients: {"servings": 4, "items": [{"name": "flour", "amount": 250, "unit": "g"}]}
    ingredients: Mapped[dict] = mapped_column(JSONB, nullable=False)

    # Optional origin URL
    source_url: Mapped[str | None] = mapped_column(String(2048), nullable=True, comment="URL where the recipe was obtained from")

    # Timing
    prep_time_minutes: Mapped[int | None] = mapped_column(Integer, nullable=True)
    cook_time_minutes: Mapped[int | None] = mapped_column(Integer, nullable=True)

    created_by: Mapped[str] = mapped_column(String, ForeignKey("users.id"), nullable=False)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False, server_default=func.now())
    updated_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False, server_default=func.now(), onupdate=func.now())
