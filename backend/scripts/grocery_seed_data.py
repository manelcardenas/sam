"""The starter grocery vocabulary — docs/plans/ingredient-capture-plan.md §3.6.

**Data, not a migration.** Same call the `cuisines` vocabulary made
(`874c491875f4`, *"new cuisines are a plain data insert later, no migration
needed"*) — but seeded from a script rather than from inside the migration,
because this list is two orders of magnitude larger and is expected to be
curated over time. Adding a row here and re-running the seed is the whole
process; `upsert_many` is idempotent and never overwrites a human confirmation.

WHAT BELONGS HERE
-----------------
Things a Catalan/Spanish household actually buys. Written in Spanish first
because that is what gets typed, with Catalan and English alongside so `huevos`
and `eggs` resolve to **one row** and therefore one shopping-list line.

`is_pantry` marks what is normally already in the house. It does **not** hide the
ingredient — it starts its line unticked in the popup, so 1 kg of sugar for a
cake is still one tap away. Mark only the genuine always-there staples: oil,
vinegar, salt, dried spices, flour, sugar, rice, pasta. Marking too much makes
the popup a wall of unticked rows and the default stops meaning anything.

`default_unit` is a hint to the parser so it writes `g` rather than `gramos`.
**NULL means counted, not measured** — which is also what makes `20 g de huevos`
detectable as a mistake.

**The bare generic matters as much as the specific one.** `Aceite de oliva` was
seeded without plain `Aceite`, which is what actually gets typed — so the line
fell into `other` and the sorting silently failed on one of the most common
ingredients there is. Where a generic word is what somebody would write on a
list, it earns its own row next to the specific ones.

This is ~275 rows rather than the 400-600 the plan estimated. Coverage of what is
cooked weekly was preferred over reaching a number: a real ingredient missing from
here costs one `✦ nuevo` badge, while a row nobody recognises costs every future
prompt a little accuracy.
"""

